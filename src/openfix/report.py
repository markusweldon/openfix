"""Human-readable output: pull request bodies and run summaries."""

from __future__ import annotations

from typing import Any

ICON = {"passed": "✅", "failed": "❌", "not_run": "⚪", "inconclusive": "⚠️"}
STATUS_TEXT = {
    "verified": "✅ Verified: every required check passed",
    "unverified": "⚠️ Unverified: some required checks could not prove the fix",
    "failed": "❌ Failed verification",
}


def pr_body(receipt: dict[str, Any], receipt_digest: str) -> str:
    f = receipt["finding"]
    loc = f.get("location") or {}
    where = (
        f"`{loc.get('path')}:{loc.get('start_line')}`"
        if loc.get("path")
        else (f"`{(f.get('package') or {}).get('name')}`")
    )
    author = receipt.get("author") or {}
    rows = "\n".join(
        f"| {ICON.get(c['status'], '')} {c['name']} | {c['status']} | {c['detail']} |" for c in receipt["checks"]
    )
    usage = author.get("usage") or {}
    model_line = (
        (
            f"`{author.get('model')}` · {author.get('turns')} turns · "
            f"{usage.get('input_tokens', 0) + usage.get('output_tokens', 0):,} tokens"
            + (f" · ${author['cost_usd']:.2f}" if author.get("cost_usd") is not None else "")
        )
        if author
        else "Deterministic upgrade (no model)"
    )
    return f"""### OpenFix: {f["title"]}

**{STATUS_TEXT.get(receipt["status"], receipt["status"])}**

| | |
|---|---|
| Finding | `{f["rule_id"]}` from **{f["tool"]}** ({f["severity"]}) at {where} |
| CWE / advisories | {", ".join(f.get("cwe") or []) or "-"} / {", ".join(f.get("advisories") or []) or "-"} |
| Fixed by | {model_line} |
| Policy rule | {receipt["policy"]["decision"]["rule"]} |
| Change | {len(receipt["patch"]["files"])} file(s), {receipt["patch"]["lines_changed"]} line(s) |

#### What changed
{receipt.get("summary") or "-"}

#### Evidence
| Check | Result | Detail |
|---|---|---|
{rows}

<details><summary>Receipt</summary>

Receipt `sha256:{receipt_digest}` · patch `sha256:{receipt["patch"]["sha256"]}`
· base `{receipt["repository"]["base_commit"]}`.
Verify locally with `openfix receipt verify <receipt-dir> --repo .`

</details>

> Generated by [OpenFix](https://github.com/markusweldon/openfix). Review the diff before merging; OpenFix never merges.
"""


def summary_markdown(outcomes: list[dict[str, Any]], meta: dict[str, Any]) -> str:
    lines = [
        f"# OpenFix run {meta['run_id']}",
        "",
        f"Repository `{meta['repo']}` at `{meta['base_commit'][:12]}` · author `{meta['author']}`"
        + (f" · reviewer `{meta['reviewer']}`" if meta.get("reviewer") else ""),
        "",
        "| Finding | Action | Result | Checks | Cost | PR |",
        "|---|---|---|---|---|---|",
    ]
    for o in outcomes:
        checks = " ".join(f"{ICON.get(c['status'], '')}{c['name']}" for c in o.get("checks", []))
        cost = f"${o['cost_usd']:.2f}" if o.get("cost_usd") is not None else "-"
        lines.append(
            f"| {o['label']} | {o['action']} | **{o['status']}** {o.get('detail') or ''} | {checks} | "
            f"{cost} | {o.get('pr_url') or ''} |"
        )
    totals = meta.get("totals", {})
    lines += [
        "",
        f"Total: {totals.get('tokens', 0):,} tokens"
        + (f", ${totals['cost_usd']:.2f}" if totals.get("cost_usd") is not None else ""),
    ]
    return "\n".join(lines) + "\n"
